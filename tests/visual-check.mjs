import { chromium, request } from 'playwright-core';
import path from 'node:path';

const output = process.argv[2] || process.cwd();
const baseURL = process.env.MAPA_BASE_URL || 'http://localhost:3000';
const edge = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const username = `visual${Date.now()}`;
const viewerUsername = `viewer${Date.now()}`;
const userIds=[];
const browser = await chromium.launch({ executablePath: edge, headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  await page.goto(baseURL);
  await page.locator('#username').fill('admin');
  await page.locator('#password').fill('123456');
  await page.locator('#loginForm button').click();
  await page.waitForSelector('#adminPage:not([hidden])');
  await page.screenshot({ path: path.join(output, 'mapa-admin.png'), fullPage: true });
  userIds.push(await page.evaluate(async credentials => {
    const response = await fetch('/api/users', { method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify(credentials) });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error);
    return data.row.id;
  }, { name:'Teste Visual', username, password:'123456', role:'EDITOR' }));
  userIds.push(await page.evaluate(async credentials => {
    const response = await fetch('/api/users', { method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify(credentials) });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error);
    return data.row.id;
  }, { name:'Teste Visualizador', username:viewerUsername, password:'123456', role:'VIEWER' }));
  await page.locator('#adminLogout').click();
  await page.locator('#username').fill(username);
  await page.locator('#password').fill('123456');
  await page.locator('#loginForm button').click();
  await page.waitForSelector('#workspace:not([hidden])');
  await page.waitForSelector('.help-dialog[open]');
  if (await page.locator('.help-dialog').getAttribute('data-role') !== 'editor') throw new Error('O guia do Editor não foi carregado');
  await page.screenshot({ path: path.join(output, 'mapa-ajuda-editor.png'), fullPage: true });
  await page.locator('.help-close').click();
  await page.waitForTimeout(600);
  if(await page.locator('#workspace .brand-icon svg').count()!==1)throw new Error('O símbolo de salas não foi aplicado à marca');
  if (await page.locator('#logsBtn').isVisible()) throw new Error('Editor não pode visualizar o histórico');
  if (!await page.locator('a[href="/api/export.docx"]').isVisible()) throw new Error('A exportação Word não está disponível');
  if (!await page.locator('a[href="/api/export.xlsx"]').isVisible()) throw new Error('A exportação Excel não está disponível');
  await page.screenshot({ path: path.join(output, 'mapa-desktop.png'), fullPage: true });
  await page.locator('#theme').click();
  await page.locator('#helpButton').click();
  await page.locator('[data-help-step="2"]').click();
  const darkPreviewColor=await page.locator('.shot-cell b').evaluate(element=>getComputedStyle(element).color);
  if(darkPreviewColor!=='rgb(23, 51, 72)')throw new Error('A prévia do destaque está sem contraste no tema escuro');
  await page.locator('[data-help-step="3"]').click();
  const confirmWidths=await page.locator('.shot-confirm-actions button').evaluateAll(buttons=>buttons.map(button=>button.getBoundingClientRect().width));
  if(confirmWidths.length!==2||Math.abs(confirmWidths[0]-confirmWidths[1])>1)throw new Error('Os botões da confirmação não estão centralizados e com a mesma largura');
  await page.screenshot({ path: path.join(output, 'mapa-ajuda-editor-dark.png'), fullPage: true });
  await page.locator('.help-close').click();
  await page.screenshot({ path: path.join(output, 'mapa-desktop-dark.png'), fullPage: true });
  await page.setViewportSize({ width:390, height:844 });
  await page.reload();
  await page.waitForSelector('#workspace:not([hidden])');
  await page.screenshot({ path: path.join(output, 'mapa-mobile.png'), fullPage: true });
  await page.locator('[data-shift="TARDE"]').click();
  await page.locator('#mobileSchedule [data-cell]').first().click();
  await page.waitForSelector('#cellDialog[open]');
  await page.screenshot({ path: path.join(output, 'mapa-mobile-editor.png'), fullPage: true });
  await page.locator('[data-close="cellDialog"]').click();
  await page.locator('#logout').click();
  await page.locator('#username').fill(viewerUsername);
  await page.locator('#password').fill('123456');
  await page.locator('#loginForm button').click();
  await page.waitForSelector('#workspace:not([hidden])');
  await page.waitForSelector('.help-dialog[open]');
  if (await page.locator('.help-dialog').getAttribute('data-role') !== 'viewer') throw new Error('O guia do Visualizador não foi carregado');
  await page.screenshot({ path: path.join(output, 'mapa-ajuda-visualizador.png'), fullPage: true });
  await page.locator('.help-close').click();
  await page.waitForTimeout(600);
  if (!await page.locator('#logsBtn').isVisible()) throw new Error('Visualizador precisa enxergar o histórico');
  if (await page.locator('#importBtn').isVisible()) throw new Error('Visualizador não pode importar arquivos');
  await page.locator('#mobileSchedule [data-cell]').first().click();
  await page.waitForSelector('#cellDialog[open]');
  await page.locator('#cellHistory').click();
  await page.waitForSelector('#historyDrawer.open');
  if(await page.locator('#cellDialog').evaluate(dialog=>dialog.open))throw new Error('A janela da sala permaneceu aberta sobre o histórico');
} finally {
  await browser.close();
  if (userIds.length) {
    const context = await request.newContext({ baseURL });
    await context.post('/api/auth/login', { data:{ username:'admin', password:'123456' } });
    for(const id of userIds) await context.delete(`/api/users/${id}`);
    await context.dispose();
  }
}
